// Writes core/Glyphs.mjs: an SVG path for every Material Design Icons glyph the core and the
// apps use, so platforms without a Nerd Font (Windows, macOS, the web) draw real icons instead
// of boxes. Run after using a new icon: npm run glyphs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const mdi = new URL("node_modules/@mdi/svg/", root);
const meta = JSON.parse(readFileSync(new URL("meta.json", mdi), "utf8"));
const byCode = new Map(meta.map((m) => [m.codepoint.toLowerCase(), m.name]));

// Every \u{f....} escape in these folders, plus extra icons asked for by name.
const SOURCES = ["core/", "desktop/ui/", "desktop/ui/shared/"];
const EXTRA = ["close", "cog"];
const ESCAPE = /\\u\{(f[0-9a-f]{3,4})\}/gi;
const codes = new Set();
for (const dir of SOURCES) {
  let names = [];
  try { names = readdirSync(new URL(dir, root)); } catch (e) { continue; }
  for (const f of names.filter((f) => /\.(mjs|js|html)$/.test(f) && f !== "Glyphs.mjs")) {
    const src = readFileSync(new URL(dir + f, root), "utf8");
    for (const m of src.matchAll(ESCAPE)) codes.add(m[1].toLowerCase().padStart(5, "0"));
  }
}

const path = (name) => readFileSync(new URL(`svg/${name}.svg`, mdi), "utf8").match(/ d="([^"]+)"/)[1];
const glyphs = {}, named = {};
for (const code of [...codes].sort()) {
  const name = byCode.get(code);
  if (!name) { console.warn(`no MDI icon for U+${code.toUpperCase()}`); continue; }
  glyphs[String.fromCodePoint(parseInt(code, 16))] = { name, d: path(name) };
}
for (const name of EXTRA) named[name] = path(name);

const out = `// Generated by scripts/make-glyphs.mjs from Material Design Icons ${JSON.parse(readFileSync(new URL("package.json", mdi), "utf8")).version}
// (Apache-2.0, https://pictogrammers.com/library/mdi/). Do not edit by hand.
// Paths are on a 24 x 24 grid.

// Nerd Font glyph (as used in the core) -> { name, d }
export const GLYPHS = ${JSON.stringify(glyphs, null, 1)};

// Extra icons by MDI name.
export const NAMED = ${JSON.stringify(named, null, 1)};

export function path(glyph) {
  const g = GLYPHS[glyph];
  return g ? g.d : NAMED[glyph] || null;
}
`;
writeFileSync(new URL("core/Glyphs.mjs", root), out);
console.log(`core/Glyphs.mjs: ${Object.keys(glyphs).length} glyphs, ${EXTRA.length} named`);
